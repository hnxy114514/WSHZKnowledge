_PY_CHARS = set("abcdefghijklmnopqrstuvwxyzāáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜü ")


def _is_note(seg):
    """括号里是不是我们插入的拼音（纯字母+声调+空格）。"""
    if not seg:
        return False
    for ch in seg:
        if ch.lower() not in _PY_CHARS:
            return False
    return True


def _add_note(body, key, off, py):
    # 新写法：第三项直接给要注音的那个字（在同一串里唯一时最稳），内部换算成插入位置
    if isinstance(off, str):
        idx = key.find(off)
        if idx < 0:
            return body
        off = idx + len(off)      # 多字词注在整个词后面（「阑珊（lán shān）」而不是「阑（lán shān）珊」）
    """在 key 的第 off 个字符之后插入「（拼音）」。

    已经插入过注音的正文里，key 可能被括号拆开（同一篇要注两个字时常发生），
    所以定位走「影子串」：先把已插入的注音整体剔掉，在干净的串上找 key，
    再映射回原串下标插入。找不到就跳过，绝不硬塞。
    """
    shadow = []
    mapping = []
    i = 0
    while i < len(body):
        if body[i] == "（":
            j = body.find("）", i)
            if j > i and _is_note(body[i + 1:j]):
                i = j + 1
                continue
        shadow.append(body[i])
        mapping.append(i)
        i += 1
    k = "".join(shadow).find(key)
    if k < 0:
        return body
    pos_sh = k + off
    if pos_sh > len(mapping):
        return body
    # off 允许等于 key 的长度（注在最后一个字之后）；这时取最后一个字的下一位，
    # 绝不能直接落到整段结尾——曾经把「谈䜩（yàn）」插到全篇末尾。
    if pos_sh < len(mapping):
        pos = mapping[pos_sh]
    elif mapping:
        pos = mapping[-1] + 1
    else:
        pos = len(body)
    return body[:pos] + "（" + py + "）" + body[pos:]


def _apply_notes():
    n = 0
    for vol in BIBEI["children"]:
        for node in vol["children"]:
            title = node["name"]
            for tkey, key, off, py in NOTES:
                if tkey not in title:
                    continue
                before = node["body"]
                node["body"] = _add_note(before, key, off, py)
                if node["body"] != before:
                    n += 1
    return n



